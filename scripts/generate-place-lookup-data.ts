/**
 * Builds components/place-lookup-data.ts, the town and ZIP table the public
 * Find a club page uses to sort clubs by distance (#2056). The lookup runs in
 * the visitor's browser, so a typed town or ZIP never reaches the server.
 *
 * Source: the GeoNames postal code file for the United States (US.txt from
 * https://download.geonames.org/export/zip/), licensed CC BY 4.0. Only Iowa and
 * Missouri rows are kept, with coordinates rounded to three decimals (about
 * 100 m), which is plenty for "which club is nearest".
 *
 * Usage: npx tsx scripts/generate-place-lookup-data.ts path/to/US.txt
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const STATES = new Set(["IA", "MO"]);

const source = process.argv[2];
if (!source) {
  console.error("Usage: npx tsx scripts/generate-place-lookup-data.ts path/to/US.txt");
  process.exit(1);
}

const rows = new Map<string, string>();
for (const line of readFileSync(source, "utf8").split("\n")) {
  const columns = line.split("\t");
  if (columns.length < 11) continue;
  const [country, zip, place, , state, , , , , latitude, longitude] = columns;
  if (country !== "US" || !STATES.has(state) || !/^\d{5}$/.test(zip)) continue;
  const lat = Number(latitude);
  const lng = Number(longitude);
  const name = place.trim();
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || !name || /[|\n`$\\]/.test(name)) continue;
  rows.set(zip, `${zip}|${name}|${state}|${lat.toFixed(3)}|${lng.toFixed(3)}`);
}

const sorted = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, row]) => row);
const output = `// Generated by scripts/generate-place-lookup-data.ts. Do not edit by hand.
// Town and ZIP locations for Iowa and Missouri from GeoNames (geonames.org),
// licensed CC BY 4.0. Each line: ZIP|Place|State|latitude|longitude.
// Loaded only in the visitor's browser, and only when they look up a town or ZIP (#2056).
export const placeLookupRows = \`${sorted.join("\n")}\`;
`;

const target = path.join(process.cwd(), "components/place-lookup-data.ts");
writeFileSync(target, output);
console.log(`Wrote ${sorted.length} rows to ${path.relative(process.cwd(), target)}`);
