import { inflateRawSync } from "node:zlib";
import { describe, expect, it } from "vitest";
import { buildArchiveContents, countCsvDataRows, eventAllowsArchiveDownload, sha256Hex } from "@/modules/reporting/event-archive";
import { buildZip, crc32 } from "@/modules/reporting/zip";

/** A minimal reader: the central directory, each entry's bytes and the CRC the directory states. */
function readZip(zip: Buffer) {
  const end = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  const count = zip.readUInt16LE(end + 10);
  let at = zip.readUInt32LE(end + 16);
  const entries: Array<{ name: string; data: Buffer; crc: number; flags: number }> = [];
  for (let i = 0; i < count; i += 1) {
    expect(zip.readUInt32LE(at)).toBe(0x02014b50);
    const flags = zip.readUInt16LE(at + 8);
    const method = zip.readUInt16LE(at + 10);
    const crc = zip.readUInt32LE(at + 16);
    const compressed = zip.readUInt32LE(at + 20);
    const size = zip.readUInt32LE(at + 24);
    const nameLength = zip.readUInt16LE(at + 28);
    const extraLength = zip.readUInt16LE(at + 30);
    const commentLength = zip.readUInt16LE(at + 32);
    const localOffset = zip.readUInt32LE(at + 42);
    const name = zip.subarray(at + 46, at + 46 + nameLength).toString("utf8");
    expect(zip.readUInt32LE(localOffset)).toBe(0x04034b50);
    const start = localOffset + 30 + zip.readUInt16LE(localOffset + 26) + zip.readUInt16LE(localOffset + 28);
    const body = zip.subarray(start, start + compressed);
    const data = method === 8 ? inflateRawSync(body) : Buffer.from(body);
    expect(data.length).toBe(size);
    entries.push({ name, data, crc, flags });
    at += 46 + nameLength + extraLength + commentLength;
  }
  return entries;
}

describe("zip writer (#175)", () => {
  it("round-trips names, bytes and CRCs, including an empty file and a UTF-8 name", () => {
    const big = Buffer.from("row,of,data\r\n".repeat(500));
    const zip = buildZip([
      { name: "a.csv", data: big },
      { name: "forms/café-responses.csv", data: new TextEncoder().encode("é") },
      { name: "empty.csv", data: new Uint8Array() },
    ], new Date("2026-11-12T18:00:00Z"));
    const entries = readZip(zip);
    expect(entries.map((entry) => entry.name)).toEqual(["a.csv", "forms/café-responses.csv", "empty.csv"]);
    expect(entries[0]!.data.equals(big)).toBe(true);
    expect(zip.length).toBeLessThan(big.length);
    expect(entries[1]!.data.toString("utf8")).toBe("é");
    expect(entries[2]!.data.length).toBe(0);
    for (const entry of entries) {
      expect(entry.crc).toBe(crc32(entry.data));
      expect(entry.flags & 0x0800).toBe(0x0800);
    }
  });

  it("computes the standard CRC-32", () => {
    expect(crc32(new TextEncoder().encode("123456789"))).toBe(0xcbf43926);
    expect(crc32(new Uint8Array())).toBe(0);
  });
});

describe("countCsvDataRows (#175)", () => {
  it("excludes the header, ignores the byte-order mark and keeps quoted newlines inside one row", () => {
    expect(countCsvDataRows("﻿\"a\",\"b\"\r\n\"1\",\"two\r\nlines\"\r\n\"3\",\"say \"\"hi\"\"\"\r\n")).toBe(2);
    expect(countCsvDataRows("a,b\r\n")).toBe(0);
    expect(countCsvDataRows("a,b\n1,2\n3,4")).toBe(2);
    expect(countCsvDataRows("")).toBe(0);
  });
});

describe("event archive contents (#175)", () => {
  it("lists the event, who and when, each file's rows and checksum, and what is left out", () => {
    const data = new TextEncoder().encode("﻿a,b\r\n1,2\r\n3,4\r\n");
    const text = buildArchiveContents({
      eventName: "Synthetic Camp", eventId: "evt_1", lifecycleState: "CLOSED", generatedBy: "Pat Staff",
      generatedAt: new Date("2026-11-12T18:30:00Z"), files: [{ name: "registrations.csv", data }],
      notIncluded: [{ name: "attendees.csv", reason: "FORBIDDEN" }, { name: "church-owed.csv", reason: "EMPTY" }],
    });
    expect(text).toContain("Event: Synthetic Camp");
    expect(text).toContain("Event ID: evt_1");
    expect(text).toContain("Generated by: Pat Staff");
    expect(text).toContain("2026-11-12T18:30:00.000Z (2026-11-12 12:30 PM CST)");
    expect(text).toContain("Health records are never included");
    expect(text).toContain("not for reimport");
    expect(text).toContain("Rows: 2");
    expect(text).toContain(`SHA-256: ${sha256Hex(data)}`);
    expect(text).toContain("attendees.csv: Not included: your role can't download this export");
    expect(text).toContain("church-owed.csv: Not included: nothing to export");
  });

  it("allows only closed or archived events", () => {
    const base = { isPublished: true, archivedAt: null };
    expect(eventAllowsArchiveDownload({ ...base, lifecycleState: "CLOSED" })).toBe(true);
    expect(eventAllowsArchiveDownload({ ...base, lifecycleState: "PUBLISHED" })).toBe(false);
    expect(eventAllowsArchiveDownload({ ...base, lifecycleState: "COMPLETE" })).toBe(false);
    expect(eventAllowsArchiveDownload({ isPublished: false, lifecycleState: "COMPLETE", archivedAt: new Date() })).toBe(true);
  });
});
