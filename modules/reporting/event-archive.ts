import { createHash } from "node:crypto";
import { calendarDateIn } from "@/modules/calendar/domain";
import { CONFERENCE_TIME_ZONE } from "@/modules/calendar/conference-format";
import { effectiveLifecycleState, eventLifecycleStateLabel, type EventLifecycleFacts } from "@/modules/events/lifecycle-state";

/**
 * The event archive (#175, first slice): one zip of an event's existing exports, with a contents page. Pure helpers:
 * which events may be archived this way, how rows are counted, and the contents text. The route decides what goes in.
 */

export const EVENT_ARCHIVE_STATES = ["CLOSED", "ARCHIVED"] as const;

/** True when the event is closed or archived, by the same reading of the stored state the rest of the app uses. */
export function eventAllowsArchiveDownload(facts: EventLifecycleFacts): boolean {
  return (EVENT_ARCHIVE_STATES as readonly string[]).includes(effectiveLifecycleState(facts));
}

export function sha256Hex(data: Uint8Array): string {
  return createHash("sha256").update(data).digest("hex");
}

/**
 * The data rows of a CSV: every record after the header, where a quoted newline stays inside its record. A leading
 * byte-order mark is ignored and a blank file has none.
 */
export function countCsvDataRows(csv: string): number {
  const text = csv.replace(/^﻿/, "");
  let records = 0;
  let inQuotes = false;
  let recordHasContent = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i]!;
    if (inQuotes) {
      if (char === '"') {
        if (text[i + 1] === '"') i += 1;
        else inQuotes = false;
      }
      continue;
    }
    if (char === '"') {
      inQuotes = true;
      recordHasContent = true;
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && text[i + 1] === "\n") i += 1;
      if (recordHasContent) records += 1;
      recordHasContent = false;
    } else {
      recordHasContent = true;
    }
  }
  if (recordHasContent) records += 1;
  return Math.max(records - 1, 0);
}

export type ArchiveFile = { name: string; data: Uint8Array };
export type ArchiveSkip = { name: string; reason: "FORBIDDEN" | "EMPTY" };

export const ARCHIVE_SKIP_TEXT: Record<ArchiveSkip["reason"], string> = {
  FORBIDDEN: "Not included: your role can't download this export",
  EMPTY: "Not included: nothing to export",
};

function centralTime(at: Date): string {
  const time = new Intl.DateTimeFormat("en-US", { timeZone: CONFERENCE_TIME_ZONE, hour: "numeric", minute: "2-digit", timeZoneName: "short" }).format(at);
  return `${calendarDateIn(at, CONFERENCE_TIME_ZONE)} ${time}`;
}

export function buildArchiveContents(input: {
  eventName: string;
  eventId: string;
  lifecycleState: ReturnType<typeof effectiveLifecycleState>;
  generatedBy: string;
  generatedAt: Date;
  files: readonly ArchiveFile[];
  notIncluded: readonly ArchiveSkip[];
}): string {
  const lines = [
    "EVENT ARCHIVE: CONTENTS",
    "",
    `Event: ${input.eventName}`,
    `Event ID: ${input.eventId}`,
    `Event state: ${eventLifecycleStateLabel(input.lifecycleState)}`,
    `Generated by: ${input.generatedBy}`,
    `Generated at: ${input.generatedAt.toISOString()} (${centralTime(input.generatedAt)})`,
    "",
    "Health records are never included in this archive. This archive is a copy to keep and read; it is not for reimport.",
    "",
    "Files (data rows exclude the header row)",
  ];
  if (input.files.length === 0) lines.push("  None.");
  for (const file of input.files) {
    const csv = new TextDecoder().decode(file.data);
    lines.push(`  ${file.name}`, `    Rows: ${countCsvDataRows(csv)}`, `    SHA-256: ${sha256Hex(file.data)}`);
  }
  lines.push("", "Not included");
  if (input.notIncluded.length === 0) lines.push("  Nothing was left out.");
  for (const skip of input.notIncluded) lines.push(`  ${skip.name}: ${ARCHIVE_SKIP_TEXT[skip.reason]}`);
  return lines.join("\r\n") + "\r\n";
}
